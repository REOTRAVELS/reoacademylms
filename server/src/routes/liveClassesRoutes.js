import { Router } from 'express';
import * as c from '../controllers/liveClassesController.js';
import { authenticate } from '../middleware/auth.js';
import { requireRole } from '../middleware/role.js';
import { requireActiveProgramEnrollment } from '../middleware/programEnrollment.js';
import { asyncHandler } from '../middleware/asyncHandler.js';

const r = Router();
r.use(authenticate);
r.use(requireActiveProgramEnrollment);
r.get('/', asyncHandler(c.listLiveClasses));
r.post('/emergency', requireRole('SUPER_ADMIN'), asyncHandler(c.createEmergencyLiveClass));
r.get('/:id/export.ics', asyncHandler(c.exportLiveClass));
r.post('/', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.createLiveClass));
r.patch('/:id/schedule', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.rescheduleLiveClass));
r.post('/:id/cancel', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.cancelLiveClass));
r.delete('/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.deletePastLiveClass));
r.post('/:id/start', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.startLiveClass));
r.post('/:id/join', asyncHandler(c.joinLiveClass));
r.post('/:id/leave', asyncHandler(c.leaveLiveClass));
r.post('/:id/end', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.endLiveClass));
r.post('/:id/recordings', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.startRecording));
r.get('/:id/recordings', asyncHandler(c.listRecordings));
r.get('/recordings/:recordingId/playback', asyncHandler(c.getRecordingPlayback));
r.post('/:id/recordings/:recordingId/stop', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.stopRecording));
r.get('/:id/report', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.getClassReport));
r.post('/:id/presences/:presenceId/verify', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.verifyPresence));
r.patch('/:id/presences/:presenceId', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.correctPresence));
export default r;
