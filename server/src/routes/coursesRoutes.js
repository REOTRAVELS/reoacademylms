import { Router } from 'express';
import * as c from '../controllers/coursesController.js';
import { createCertificate, listCertificates, downloadCertificate } from '../controllers/certificateController.js';
import { authenticate } from '../middleware/auth.js';
import { requireRole } from '../middleware/role.js';
import { requireActiveProgramEnrollment } from '../middleware/programEnrollment.js';
import { asyncHandler } from '../middleware/asyncHandler.js';

const r = Router();
r.use(authenticate);
r.use(requireActiveProgramEnrollment);
r.get('/', asyncHandler(c.listCourses));
r.get('/assignments', asyncHandler(c.listAssignments));
r.get('/assignments/:id', asyncHandler(c.getAssignment));
r.get('/certificates', asyncHandler(listCertificates));
r.get('/certificates/download/:fileName', asyncHandler(downloadCertificate));
r.get('/lessons/:id', asyncHandler(c.getLesson));
r.get('/:id/quality', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.getCourseQuality));
r.get('/:id/preview', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.previewCourse));
r.post('/:id/publish', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.publishCourse));
r.post('/:id/unpublish', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.unpublishCourse));
r.post('/:id/archive', requireRole('SUPER_ADMIN'), asyncHandler(c.archiveCourse));
r.put('/:id/modules/order', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.reorderModules));
r.put('/modules/:moduleId/lessons/order', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.reorderLessons));
r.post('/', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.createCourse));
r.put('/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.updateCourse));
r.delete('/:id', requireRole('SUPER_ADMIN'), asyncHandler(c.deleteCourse));
r.post('/:courseId/modules', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.createModule));
r.post('/modules/:moduleId/lessons', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.createLesson));
r.put('/modules/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.updateModule));
r.delete('/modules/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.deleteModule));
r.put('/lessons/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.updateLesson));
r.delete('/lessons/:id', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.deleteLesson));
r.post('/:courseId/assignments', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.createAssignment));
r.post('/assignments/:id/submit', requireRole('STUDENT'), asyncHandler(c.submitAssignment));
r.post('/submissions/:submissionId/grade', authenticate, requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.gradeAssignment));
r.post('/submissions/:submissionId/release', requireRole('SUPER_ADMIN', 'TRAINER'), asyncHandler(c.releaseAssignmentGrade));
r.post('/:courseId/certificates', requireRole('SUPER_ADMIN'), asyncHandler(createCertificate));
r.get('/:id', asyncHandler(c.getCourse));
export default r;
